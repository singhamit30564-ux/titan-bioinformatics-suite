"""📄 Ask a Paper — Fetch and explain research papers by DOI / arXiv ID / bioRxiv URL.

Uses free APIs (arXiv, bioRxiv) when available, with honest template-based
explanation when GROQ_API_KEY is absent.  All data stays in-RAM (ZDR).
"""
from __future__ import annotations

import json
import os
import re
import urllib.request
import urllib.error
import xml.etree.ElementTree as ET

import streamlit as st

from titan_utils.i18n import t
from titan_utils.ui import dr_titan_tip, titan_title

titan_title(
    "📄",
    "Ask a Paper",
    "Paste a DOI, arXiv ID, or bioRxiv URL — Dr. Titan explains it in simple English or Hindi.",
)

st.info(t(
    "🌐 **Online only** — this tool fetches paper metadata from arXiv/bioRxiv APIs. "
    "Results are stored in-RAM only (Zero Data Retention)."
))

# ── Helpers ──────────────────────────────────────────────────────────────────

def _extract_arxiv_id(text: str) -> str | None:
    """Return arXiv ID from a URL or bare ID string."""
    m = re.search(r"(\d{4}\.\d{4,5})(v\d+)?", text)
    return m.group(0) if m else None


def _extract_doi(text: str) -> str | None:
    """Return DOI string from a URL or bare DOI."""
    m = re.search(r"(10\.\d{4,9}/[^\s]+)", text)
    return m.group(1) if m else None


def _extract_biorxiv_id(text: str) -> str | None:
    """Return bioRxiv content ID from a URL."""
    m = re.search(r"biorxiv\.org/content/(?:.*?)(\d{5,})(?:v\d+)?", text)
    return m.group(1) if m else None


def _fetch_arxiv(arxiv_id: str) -> dict | None:
    """Fetch metadata from the arXiv Atom API."""
    url = f"http://export.arxiv.org/api/query?id_list={arxiv_id}"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "TitanBioinformatics/1.0"})
        with urllib.request.urlopen(req, timeout=10) as resp:
            root = ET.fromstring(resp.read())
        ns = {"atom": "http://www.w3.org/2005/Atom"}
        entry = root.find("atom:entry", ns)
        if entry is None:
            return None
        title = entry.findtext("atom:title", "", ns).strip()
        abstract = entry.findtext("atom:summary", "", ns).strip()
        authors = [a.findtext("atom:name", "", ns) for a in entry.findall("atom:author", ns)]
        published = entry.findtext("atom:published", "", ns)[:10]
        return {"title": title, "abstract": abstract, "authors": authors[:5], "date": published, "source": f"arXiv:{arxiv_id}"}
    except (urllib.error.URLError, ET.ParseError, Exception):
        return None


def _fetch_biorxiv(biorxiv_id: str) -> dict | None:
    """Fetch metadata from the bioRxiv API detail endpoint."""
    url = f"https://api.biorxiv.org/details/biorxiv/{biorxiv_id}"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "TitanBioinformatics/1.0"})
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read())
        messages = data.get("collection", [])
        if not messages:
            return None
        paper = messages[0]
        return {
            "title": paper.get("title", "Untitled"),
            "abstract": paper.get("abstract", "Abstract not available."),
            "authors": paper.get("authors", "Unknown").split(";")[:5],
            "date": paper.get("date", ""),
            "source": f"bioRxiv:{biorxiv_id}",
        }
    except (urllib.error.URLError, json.JSONDecodeError, Exception):
        return None


def _template_explain(abstract: str, language: str = "en") -> str:
    """Produce a template-based simplified explanation (no LLM)."""
    sentences = [s.strip() for s in re.split(r"[.!?]", abstract) if len(s.strip()) > 20]
    key_points = sentences[:5]
    if language == "hi":
        header = "## 🤖 डॉ. टाइटन का सरल सारांश (टेम्पलेट-आधारित)"
        body = "\n".join(f"- {p}" for p in key_points)
        label = (
            "\n\n---\n⚠️ **ईमानदार लेबल:** यह सारांश AI द्वारा नहीं, बल्कि अमूर्त (abstract) के "
            "वाक्यों को सरल बनाकर तैयार किया गया है। GROQ_API_KEY सेट करने पर AI-आधारित व्याख्या मिलेगी।"
        )
    else:
        header = "## 🤖 Dr. Titan's Simplified Summary (template-based)"
        body = "\n".join(f"- {p}" for p in key_points)
        label = (
            "\n\n---\n⚠️ **Honest label:** This summary is generated by extracting key sentences from the "
            "abstract — not by an LLM. Set GROQ_API_KEY for a natural-language AI explanation."
        )
    return f"{header}\n{body}{label}"


def _groq_explain(abstract: str, language: str = "en") -> str:
    """Use Groq API for a proper explanation if key is available."""
    api_key = os.environ.get("GROQ_API_KEY", "")
    if not api_key:
        return ""
    if language == "hi":
        sys_prompt = "Tum Dr. Titan ho. Ek research paper ka abstract Hindi mein saral bhasha mein samjhao — jaise 12 saal ke bacche ko padha rahe ho. 5 bullet points mein."
    else:
        sys_prompt = "You are Dr. Titan. Explain this research paper abstract in simple English suitable for a 12-year-old. Use 5 bullet points. Be accurate and honest."
    try:
        payload = json.dumps({
            "model": "llama3-8b-8192",
            "messages": [
                {"role": "system", "content": sys_prompt},
                {"role": "user", "content": abstract[:3000]},
            ],
            "temperature": 0.3,
            "max_tokens": 500,
        }).encode()
        req = urllib.request.Request(
            "https://api.groq.com/openai/v1/chat/completions",
            data=payload,
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=15) as resp:
            result = json.loads(resp.read())
        content = result["choices"][0]["message"]["content"]
        label = "\n\n---\n✅ **AI-powered explanation** via Groq (GROQ_API_KEY detected)."
        return f"## 🤖 Dr. Titan's Explanation\n{content}{label}"
    except Exception:
        return ""


# ── UI ───────────────────────────────────────────────────────────────────────
query = st.text_input(
    t("Paste a DOI, arXiv ID, or bioRxiv URL:"),
    placeholder="e.g. 2401.12345 or 10.1101/2024.01.01.123456 or https://arxiv.org/abs/2401.12345",
)

language = st.radio(t("Explanation language:"), ["English", "हिंदी"], horizontal=True)
lang_code = "hi" if "हिंदी" in language else "en"

if st.button(t("🔬 Fetch & Explain"), type="primary", use_container_width=True) and query.strip():
    paper = None
    source_label = ""

    arxiv_id = _extract_arxiv_id(query)
    doi = _extract_doi(query)
    biorxiv_id = _extract_biorxiv_id(query)

    if arxiv_id:
        source_label = f"arXiv:{arxiv_id}"
        with st.spinner(t("Fetching from arXiv API...")):
            paper = _fetch_arxiv(arxiv_id)
    elif biorxiv_id:
        source_label = f"bioRxiv:{biorxiv_id}"
        with st.spinner(t("Fetching from bioRxiv API...")):
            paper = _fetch_biorxiv(biorxiv_id)
    elif doi:
        source_label = f"DOI:{doi}"
        st.warning(t(
            "⚠️ Direct DOI lookup is not supported without a CrossRef key. "
            "Try searching on arXiv or bioRxiv and paste that URL/ID instead."
        ))
    else:
        st.error(t("❌ Could not parse a valid DOI, arXiv ID, or bioRxiv URL. Please check and try again."))

    if paper:
        st.markdown(f"### 📑 {paper['title']}")
        st.caption(f"**Source:** {paper['source']} | **Date:** {paper['date']}")
        st.caption(f"**Authors:** {', '.join(paper['authors'])}")
        with st.expander(t("📖 Original Abstract"), expanded=False):
            st.write(paper["abstract"])

        # Explanation
        explanation = _groq_explain(paper["abstract"], lang_code)
        if not explanation:
            explanation = _template_explain(paper["abstract"], lang_code)
        st.markdown(explanation)

        # ZDR notice
        st.caption(t("🛡️ All data processed in-RAM only — Zero Data Retention."))

dr_titan_tip(
    "When reading papers, start with the abstract, then look at figures and figure legends — "
    "they tell the story. Only then read the methods if you want to reproduce the work."
)