def normalize_language(language: str | None) -> str:
    """Return the canonical display label for English or Hindi."""
    value = (language or "").strip().casefold()
    if value in {"hi", "hindi", "हिंदी".casefold()}:
        return HINDI
    return ENGLISH


def get_language(state: Mapping[str, Any] | None = None) -> str:
    """Read the current Streamlit language, defaulting safely to English."""
    if state is None:
        try:
            import streamlit as st

            state = st.session_state
        except Exception:  # pragma: no cover - Streamlit is optional for helpers
            state = {}
    return normalize_language(state.get("app_language", ENGLISH))


